export type ProjectType = {
  id: string
  title: string
  hint: string
  icon: 'landing' | 'corporate' | 'shop' | 'product'
  /** Нижняя граница вилки, ₽. */
  base: number
  /**
   * Коэффициент верхней границы. Без него у типа нет потолка: в смете
   * показывается только «от» — так у сложных проектов вилка не превращается
   * в пугающее число, которое всё равно ничего не обещает.
   */
  spread?: number
  weeks: [number, number]
  includes: string[]
  /**
   * Опции, которые тип проекта закрывает сам. Их не предлагают доплатой,
   * а показывают в составе — и в расчёт они не идут, даже если посетитель
   * успел отметить их на другом типе.
   */
  includedOptions?: string[]
}

